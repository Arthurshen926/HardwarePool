#!/usr/bin/env python3
"""Compare javac -h declarations with llvm-nm --defined-only --dynamic output.

This checks exported JNI symbol names in the cross-built Android shared library.
It does not load that library, validate full runtime argument ABI compatibility,
invoke Java native methods, or establish Android/device/hardware acceptance.
Inputs are generated build artifacts, not credential or configuration files.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys


def declared_symbols(header: str) -> set[str]:
    """Read ordinary javac-generated native declarations, failing closed."""
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", header, flags=re.DOTALL)
    declarations = re.findall(
        r"\bJNIEXPORT\s+\w+\s+JNICALL\s+(Java_[A-Za-z0-9_]+)\s*\(", source
    )
    if not declarations:
        raise ValueError("generated header contains no JNI declarations")
    if len(declarations) != len(re.findall(r"\bJNIEXPORT\b", source)):
        raise ValueError("generated header contains an unrecognized JNI declaration")
    if len(declarations) != len(set(declarations)):
        raise ValueError("generated header contains duplicate JNI declarations")
    return set(declarations)


def exported_symbols(symbols: str) -> set[str]:
    """Accept only defined global text/weak function symbols, not U/data entries."""
    exports = re.findall(
        r"^[0-9a-fA-F]+\s+[TW]\s+(Java_[A-Za-z0-9_]+)\s*$", symbols, re.MULTILINE
    )
    if not exports:
        raise ValueError("shared library has no defined JNI function exports")
    if len(exports) != len(set(exports)):
        raise ValueError("symbol listing contains duplicate JNI function exports")
    return set(exports)


def check_exports(header: str, symbols: str) -> int:
    expected = declared_symbols(header)
    available = exported_symbols(symbols)
    missing = sorted(expected - available)
    if missing:
        raise ValueError("missing defined JNI function exports: " + ", ".join(missing))
    return len(expected)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("header", type=Path, help="header generated by javac -h")
    parser.add_argument("symbols", type=Path, help="llvm-nm --defined-only --dynamic output")
    args = parser.parse_args()
    try:
        count = check_exports(
            args.header.read_text(encoding="utf-8"),
            args.symbols.read_text(encoding="utf-8"),
        )
    except (OSError, UnicodeError, ValueError) as error:
        print(f"Android JNI export check: FAIL ({error})", file=sys.stderr)
        return 1
    print(f"Android JNI export check: PASS ({count} Java native declarations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
